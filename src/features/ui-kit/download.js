import { createZip } from './zip.js';
import { loadSources } from './useSource.js';

const imports = (code) => [...code.matchAll(/from\s+'([^']+)'/g)].map((m) => m[1]);

/** Bundles a documented component for download: the usage example, the real source files and a short README. */
export async function downloadEntryZip(entry, values) {
  const paths = entry.source ? [].concat(entry.source) : [];
  const sources = await loadSources(paths);
  const usage = typeof entry.usage === 'function' ? entry.usage(values) : entry.usage;

  const all = new Set(sources.flatMap((s) => imports(s.code)));
  const packages = [...all].filter((i) => !i.startsWith('.')).sort();
  const local = [...all].filter((i) => i.startsWith('.')).sort();

  const readme = [
    `# ${entry.name}`,
    '',
    entry.description,
    '',
    '## What is in this zip',
    '- `usage.jsx`  a short example of using it',
    ...sources.map((s) => `- \`${s.path.replace('src/components/', 'components/')}\`  the component source`),
    '',
    '## Needs',
    packages.length ? `Packages: ${packages.join(', ')}` : 'No extra packages.',
    local.length ? `\nProject files these import (copy them too, or adjust the paths):\n${local.map((l) => `- ${l}`).join('\n')}` : '',
    '',
    'Styling uses the Testflow design tokens (Tailwind v4 with the CSS variables in `src/global.css`).',
    'Generated by the Testflow UI Kit.',
    '',
  ].join('\n');

  const blob = createZip([
    { name: 'README.md', content: readme },
    { name: 'usage.jsx', content: usage },
    ...sources.map((s) => ({ name: s.path.replace('src/', ''), content: s.code })),
  ]);

  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `testflow-${entry.id}.zip`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
